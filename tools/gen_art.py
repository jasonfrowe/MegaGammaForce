#!/usr/bin/env python3
"""Generate every graphic asset for MegaGammaForce.

Art that every stage uses stays in XRAM the whole game. Art for one stage
(its tiles, maps, boss and palettes) is packed into that stage's bank,
which the game loads from the ROM when the stage starts.

Writes:
  images/<sheet>.png         resident sprite sheets, frames left to right
                             (edit these in Aseprite; the build converts them)
  images/palettes.bin        resident palettes, then stage 1's stage palettes
  images/stage<N>/*.png      the stage's sheets and tile sets
  images/stage<N>/*.bin      the stage's tile maps and palettes
  images/stage<N>/bank.json  what tools/mkbank.py packs into stage<N>.bin
  src/gen/assets.h           sizes, frame counts and palette indices
  src/gen/stage<N>.h         offsets of everything in the stage's bank
  src/gen/stage<N>_data.h    checks that the stage's enemy types match enemies.h

Usage: .venv/bin/python tools/gen_art.py [--preview DIR]
"""

import argparse
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "art"))

import numpy as np  # noqa: E402

import airpath  # noqa: E402
import enemies  # noqa: E402
import fx  # noqa: E402
import hud  # noqa: E402
import palettes  # noqa: E402
import ships  # noqa: E402
import stages  # noqa: E402
from kit import save_indexed, sheet  # noqa: E402

IMAGES = ROOT / "images"
GEN = ROOT / "src" / "gen"
HEADER = "/* Generated by tools/gen_art.py. Do not edit; regenerate instead. */"


def sheet_defines(prefix, frames, idx):
    fh, fw = frames[0].shape
    for f in frames:
        assert f.shape == (fh, fw), prefix
        assert f.max() < 16, prefix
    out = [
        f"#define {prefix}_W {fw}",
        f"#define {prefix}_H {fh}",
        f"#define {prefix}_FRAMES {len(frames)}",
        f"#define {prefix}_FRAME_BYTES {fw * fh // 2}",
    ]
    out += [f"#define {prefix}_{k} {v}" for k, v in idx.items()]
    return out


def palette_blob(pals):
    blob = bytearray()
    for pname, pal in pals:
        assert len(pal) == 16, pname
        for c in pal:
            blob += struct.pack("<H", palettes.rgb555(c))
    return bytes(blob)


# Enemy types and chain colors as the C enums number them (enemies.h,
# game.h); stage<N>_data.h checks them with _Static_assert.
ENEMY_TYPES = ["ET_NONE", "ET_DART", "ET_SAUCER", "ET_DRONE", "ET_GUNSHIP", "ET_TURRET", "ET_TANK", "ET_WASP",
               "ET_GUNBOAT", "ET_TRAIN"]
COLORS = ["COL_RED", "COL_BLUE", "COL_YELLOW", "COL_GRAY"]


def script_blob(st):
    """The stage's script, read into RAM when it loads: wave and ground
    counts, then waves (wave_t, 9 bytes) and ground units (ground_t, 6)."""
    waves, ground = sorted(st.get("waves", []), key=lambda w: w[0]), sorted(st.get("ground", []))
    assert len(waves) <= 48 and len(ground) <= 64, "more than stage.h's WAVES_MAX or GROUND_MAX"
    out = bytearray([len(waves), len(ground)])
    for at, t, c, x, dx, count, gap, param in waves:
        out += struct.pack("<HBBBbBBB", at, ENEMY_TYPES.index(t), COLORS.index(c), x, dx, count, gap, param)
    for y, x, t, c, param in ground:
        out += struct.pack("<HBBBB", y, x, ENEMY_TYPES.index(t), COLORS.index(c), param)
    if len(out) & 1:
        out.append(0)
    return bytes(out)


def write_bank(kind, n, items, pals, d, h, pfx, preview):
    """Pack items (sheets and binaries) for one ROM file; returns its spec and size."""
    out = []
    off = 0
    for it in items:
        name = it["name"]
        up = f"{pfx}_{name.upper()}"
        h.append(f"#define {up} {off}")
        if "frames" in it:
            frames = it["frames"]
            save_indexed(d / f"{name}.png", sheet(frames), palettes.view(it["pal"]))
            h += sheet_defines(up, frames, it.get("idx", {}))
            fh, fw = frames[0].shape
            size = fw * fh // 2 * len(frames)
            out.append({"png": f"images/stage{n}/{name}.png", "w": fw, "h": fh, "frames": len(frames),
                        "offset": off, "size": size})
            if preview:
                from preview import preview as pv
                pv(Path(preview) / f"stage{n}_{name}.png", frames, it["pal"], scale=3 if fw >= 32 else 4)
        else:
            data = bytes(it["data"])
            (d / f"{name}.bin").write_bytes(data)
            size = len(data)
            out.append({"bin": f"images/stage{n}/{name}.bin", "offset": off, "size": size})
        assert size % 2 == 0, name
        off += size
        h.append("")
    (d / f"{kind}_palettes.bin").write_bytes(palette_blob(pals))
    spec = {"palettes": f"images/stage{n}/{kind}_palettes.bin", "items": out, "size": off}
    (d / f"{kind}.json").write_text(json.dumps(spec, indent=1) + "\n")
    return off


def write_stage(st, preview):
    """A stage's two ROM files: stage<N>.bin (its script, ground and sky, with
    the TILES and SKY palettes) and boss<N>.bin (its boss, with the LAYER,
    BOSS and BOSS_WRECK palettes). Items with "boss": True go in the second."""
    n = st["n"]
    if "sky_check" in st:
        smap, solid, sky_speed = st["sky_check"]
        bad = airpath.plan(airpath.Sky(smap, solid, sky_speed), st["waves"])
        if bad:
            sys.exit(airpath.report(n, bad))
    d = IMAGES / f"stage{n}"
    d.mkdir(exist_ok=True)
    for old in ("bank.json", "palettes.bin"):
        if (d / old).exists():
            (d / old).unlink()
    h = [HEADER, f"#ifndef GEN_STAGE{n}_H", f"#define GEN_STAGE{n}_H", "",
         "/* Offsets in XRAM_BANK (S<N>_) and XRAM_BOSS (B<N>_). */", ""]
    for it in st["items"]:
        it.setdefault("pal", st["palettes"]["BOSS"])
    script = {"name": "script", "data": script_blob(st)}
    stage_items = [script] + [it for it in st["items"] if not it.get("boss")]
    boss_items = [it for it in st["items"] if it.get("boss")]
    pal = lambda names: [(nm, st["palettes"].get(nm, palettes.BLANK)) for nm in names]  # noqa: E731
    s_size = write_bank("stage", n, stage_items, pal(palettes.STAGE_SLOTS[:2]), d, h, f"S{n}", preview)
    b_size = write_bank("boss", n, boss_items, pal(palettes.STAGE_SLOTS[2:]), d, h, f"B{n}", preview)
    h.append(f"#define S{n}_BANK_BYTES {s_size}")
    h.append(f"#define B{n}_BANK_BYTES {b_size}")
    for k, v in st.get("defines", {}).items():
        h.append(f"#define S{n}_{k} {v}")
    h += ["", "#endif", ""]
    (GEN / f"stage{n}.h").write_text("\n".join(h))
    checks = sorted({w[1] for w in st.get("waves", [])} | {g[2] for g in st.get("ground", [])})
    data = [HEADER] + [f"_Static_assert({t} == {ENEMY_TYPES.index(t)}, \"gen_art.py's ENEMY_TYPES is out of date\");"
                       for t in checks]
    (GEN / f"stage{n}_data.h").write_text("\n".join(data) + "\n")
    if preview:
        for name, (img, pal_) in st.get("previews", {}).items():
            from preview import preview as pv
            pv(Path(preview) / f"stage{n}_{name}.png", [img], pal_, scale=2)
    print(f"stage {n}: stage file {s_size} bytes, boss file {b_size} bytes")
    return s_size, b_size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", help="also write enlarged RGB previews into this folder")
    args = ap.parse_args()
    IMAGES.mkdir(exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)
    if args.preview:
        Path(args.preview).mkdir(parents=True, exist_ok=True)

    dart, saucer, drone, turret = enemies.dart(), enemies.saucer(), enemies.drone(), enemies.turret_frames()
    tank, wasp = enemies.tank_frames(), enemies.wasp()
    e16 = dart + saucer + drone + turret + tank + wasp
    e16_idx = {"DART": 0, "SAUCER": 2, "DRONE": 6, "TURRET": 8, "TANK": 16, "WASP": 24}
    assert len(dart + saucer + drone + turret) == 16 and len(tank) == 8

    banner_word, banner_nums = hud.banner()
    warn_a, warn_b = hud.warning()

    # name, palette (for the PNG only), frames, {frame-index names}
    sheets = [
        ("player", palettes.PLAYER, ships.player_frames(), {}),
        ("flame", palettes.PLAYER, ships.flame_frames(), {}),
        ("vulcan", palettes.SHOTS, fx.vulcan_frames(), {}),
        ("shot8", palettes.SHOTS, fx.shot8_frames(), {"SPREAD": 0, "HOMING": 2, "SPARK": 4, "BACK": 6}),
        ("sword", palettes.SHOTS, fx.sword_frames(), {}),
        ("beam", palettes.SHOTS, fx.beam_frames(), {}),
        ("missile", palettes.SHOTS, fx.missile_frames(), {}),
        ("lock", palettes.SHOTS, fx.lock_frames(), {}),
        ("enemy16", palettes.ENEMY_RED, e16, e16_idx),
        ("enemy32", palettes.ENEMY_YELLOW, enemies.gunship() + enemies.gunboat(), {"GUNSHIP": 0, "GUNBOAT": 2}),
        ("bullet8", palettes.BULLET_PINK, fx.bullet8_frames(), {"ORB": 0, "NEEDLE": 2}),
        ("bullet16", palettes.BULLET_PINK, fx.bullet16_frames(), {}),
        ("expl16", palettes.EXPLOSION, fx.explosion_frames(16, 3), {}),
        ("expl32", palettes.EXPLOSION, fx.explosion_frames(32, 5), {}),
        ("miniship", palettes.PLAYER, hud.mini_ship(), {}),
        ("gem", palettes.ENEMY_RED, hud.gems(), {}),
        ("icons", palettes.SHOTS, hud.weapon_icons(), {}),
        ("digits", palettes.SHOTS, hud.digits(False) + hud.digits(True), {"GOLD": 10}),
        ("banner", palettes.SHOTS, banner_word, {}),
        ("bannernum", palettes.SHOTS, banner_nums, {}),
        ("warn_a", palettes.SHOTS, warn_a, {}),
        ("warn_b", palettes.SHOTS, warn_b, {}),
    ]

    h = [HEADER, "#ifndef GEN_ASSETS_H", "#define GEN_ASSETS_H", ""]
    for name, pal, frames, idx in sheets:
        save_indexed(IMAGES / f"{name}.png", sheet(frames), palettes.view(pal))
        h += sheet_defines(name.upper(), frames, idx)
        h.append("")
        if args.preview:
            from preview import preview
            preview(Path(args.preview) / f"{name}.png", frames, pal, scale=4)

    for i, (pname, _) in enumerate(palettes.ALL):
        h.append(f"#define PAL_{pname} {i}")
    h += [f"#define PAL_COUNT {len(palettes.ALL)}",
          f"#define PAL_STAGE {len(palettes.RESIDENT)} /* first of the palettes a stage loads */",
          f"#define PAL_STAGE_N {len(palettes.STAGE_SLOTS)}", ""]
    (IMAGES / "palettes.bin").write_bytes(palette_blob(palettes.ALL))

    sizes = [write_stage(st, args.preview) for st in stages.all_stages()]
    h += [f"#define STAGE_COUNT {len(sizes)}",
          f"#define STAGE_BANK_MAX {max(s for s, _ in sizes)} /* the largest stage file, less its palettes */",
          f"#define BOSS_BANK_MAX {max(b for _, b in sizes)} /* the largest boss file, less its palettes */",
          "", "#endif", ""]
    (GEN / "assets.h").write_text("\n".join(h))
    print(f"wrote {len(sheets)} resident sheets, {len(palettes.ALL)} palettes")


if __name__ == "__main__":
    main()
