#!/usr/bin/env python3
"""Generate every graphic asset for MegaGammaForce.

Writes:
  images/<sheet>.png     indexed sprite/tile sheets, frames left to right
                         (edit these in Aseprite; the build converts them)
  images/palettes.bin    every palette, RGB555 + alpha, in palettes.ALL order
  images/stage1_map.bin  the stage 1 Mode 2 tile map, top row first
  src/gen/assets.h       sizes, frame counts and frame indices for the C code

Usage: .venv/bin/python tools/gen_art.py [--preview DIR]
"""

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "art"))

import numpy as np  # noqa: E402

import boss  # noqa: E402
import enemies  # noqa: E402
import fx  # noqa: E402
import logo  # noqa: E402
import palettes  # noqa: E402
import ships  # noqa: E402
import tiles  # noqa: E402
from kit import save_indexed, sheet  # noqa: E402

IMAGES = ROOT / "images"
GEN = ROOT / "src" / "gen"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", help="also write 4x RGB previews into this folder")
    args = ap.parse_args()
    IMAGES.mkdir(exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)

    dart, saucer, drone, turret = enemies.dart(), enemies.saucer(), enemies.drone(), enemies.turret_frames()
    shot8 = fx.shot8_frames()
    tl, tile_ids, stage_map, hatches = tiles.stage1()

    # name, palette (for the PNG only), frames, {frame-index names}
    sheets = [
        ("player", palettes.PLAYER, ships.player_frames(), {}),
        ("flame", palettes.PLAYER, ships.flame_frames(), {}),
        ("vulcan", palettes.SHOTS, fx.vulcan_frames(), {}),
        ("shot8", palettes.SHOTS, shot8, {"SPREAD": 0, "HOMING": 2, "SPARK": 4, "BACK": 6}),
        ("sword", palettes.SHOTS, fx.sword_frames(), {}),
        ("beam", palettes.SHOTS, fx.beam_frames(), {}),
        ("logo", palettes.BOSS, logo.logo(), {}),
        ("enemy16", palettes.ENEMY_RED, dart + saucer + drone + turret,
         {"DART": 0, "SAUCER": 2, "DRONE": 6, "TURRET": 8}),
        ("enemy32", palettes.ENEMY_YELLOW, enemies.gunship(), {"GUNSHIP": 0}),
        ("bullet8", palettes.BULLET_PINK, fx.bullet8_frames(), {"ORB": 0, "NEEDLE": 2}),
        ("bullet16", palettes.BULLET_PINK, fx.bullet16_frames(), {}),
        ("expl16", palettes.EXPLOSION, fx.explosion_frames(16, 3), {}),
        ("expl32", palettes.EXPLOSION, fx.explosion_frames(32, 5), {}),
        ("boss_core", palettes.BOSS, boss.core(), {}),
        ("boss_wing", palettes.BOSS, boss.wing(), {}),
        ("boss_cannon", palettes.BOSS, boss.cannon(), {}),
        ("boss_turret", palettes.BOSS, boss.turret(), {}),
        ("tiles", palettes.TILES, tl, {}),
    ]

    h = [
        "/* Generated by tools/gen_art.py. Do not edit; regenerate instead. */",
        "#ifndef GEN_ASSETS_H",
        "#define GEN_ASSETS_H",
        "",
    ]
    for name, pal, frames, idx in sheets:
        fh, fw = frames[0].shape
        for f in frames:
            assert f.shape == (fh, fw), name
            assert f.max() < 16, name
        save_indexed(IMAGES / f"{name}.png", sheet(frames), palettes.view(pal))
        up = name.upper()
        h += [
            f"#define {up}_W {fw}",
            f"#define {up}_H {fh}",
            f"#define {up}_FRAMES {len(frames)}",
            f"#define {up}_FRAME_BYTES {fw * fh // 2}",
        ]
        for k, v in idx.items():
            h.append(f"#define {up}_{k} {v}")
        h.append("")
        if args.preview:
            from preview import preview
            preview(Path(args.preview) / f"{name}.png", frames, pal, scale=4)

    # Palettes.
    blob = bytearray()
    for i, (pname, pal) in enumerate(palettes.ALL):
        assert len(pal) == 16, pname
        for c in pal:
            blob += struct.pack("<H", palettes.rgb555(c))
        h.append(f"#define PAL_{pname} {i}")
    h.append(f"#define PAL_COUNT {len(palettes.ALL)}")
    h.append("")
    (IMAGES / "palettes.bin").write_bytes(bytes(blob))

    # Stage map.
    (IMAGES / "stage1_map.bin").write_bytes(stage_map.astype(np.uint8).tobytes())
    h += [
        f"#define STAGE1_MAP_COLS {stage_map.shape[1]}",
        f"#define STAGE1_MAP_ROWS {stage_map.shape[0]}",
        f"#define STAGE1_LOOP_ROWS {tiles.LOOP_ROWS}",
        f"#define TILE_SEA0 {tile_ids['sea0']}",
        "",
        "#endif",
        "",
    ]
    (GEN / "assets.h").write_text("\n".join(h))

    # Ground turrets sit on the hatches. Y is the turret center measured up from
    # the bottom of the map; the stage spawns it as Y scrolls onto the screen.
    g = sorted(((r + 1) * 16, (c + 1) * 16) for r, c in hatches)
    gl = ["/* Generated by tools/gen_art.py. Do not edit; regenerate instead. */",
          "/* Ground turret emplacements: {map y from the bottom, playfield x}. */",
          f"#define STAGE1_GROUND_N {len(g)}",
          "static const uint16_t stage1_ground[STAGE1_GROUND_N][2] = {"]
    gl += [f"    {{{y}, {x}}}," for y, x in g]
    gl += ["};", ""]
    (GEN / "stage1_ground.h").write_text("\n".join(gl))
    print(f"wrote {len(sheets)} sheets, {len(palettes.ALL)} palettes, map {stage_map.shape}")


if __name__ == "__main__":
    main()
