#!/usr/bin/env python3
"""Generate src/gen/tables.c: trig tables for the 6502.

Angles are bytes, 256 to a circle: 0 right, 64 down, 128 left, 192 up
(screen y grows downward).
  cos8[a]          round(127 * cos(a))
  atan16[dy][dx]   angle of (dx, dy) for 0 <= dx, dy < 16, in 0..64
"""

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "gen" / "tables.c"


def main():
    cos8 = [round(127 * math.cos(a * 2 * math.pi / 256)) for a in range(256)]
    atan = []
    for dy in range(16):
        for dx in range(16):
            if dx == 0 and dy == 0:
                atan.append(0)
            else:
                atan.append(round(math.atan2(dy, dx) * 256 / (2 * math.pi)) & 0xFF)
    lines = ["/* Generated by tools/gen_tables.py. Do not edit. */", "#include <stdint.h>", ""]
    lines.append("const int8_t cos8[256] = {")
    for i in range(0, 256, 16):
        lines.append("    " + ", ".join(str(v) for v in cos8[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("const uint8_t atan16[256] = {")
    for i in range(0, 256, 16):
        lines.append("    " + ", ".join(str(v) for v in atan[i:i + 16]) + ",")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
